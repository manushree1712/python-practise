# a coffee costs 291 to make and sells for 477. calculate the profit per 
#  cup and total profit if you sell 85 cups in a day

cost_price = 291
selling_price = 477
total_profit = selling_price-cost_price
total_cups = 85

profit_1_cup = total_profit
print(f"coffee  profit for one cup: {profit_1_cup}")

profit_85_cups = total_cups*total_profit
print(f"coffee profit for 85 cup: {profit_85_cups}")